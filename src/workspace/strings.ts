const systemLocale = navigator.language.split('-')[0] === 'it' ? 'it' : 'en';
export let locale: 'en' | 'it' = systemLocale;
export let strings = locale === 'it' ? italian : english;

export function applyLocale(language: 'system' | 'it' | 'en') {
  locale = language === 'system' ? systemLocale : language;
  strings = locale === 'it' ? italian : english;
  document.documentElement.lang = locale;
}
